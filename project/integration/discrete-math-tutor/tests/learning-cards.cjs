const assert=require('node:assert/strict');
const {render}=require('../frontend/learning-cards.js');
const base={schema:'learning-cards/v1',card_id:'stable-card',revision:1,title:'变量'};
assert.equal(render(null),'');
assert.equal(render([{...base,kind:'script',body:'<script>alert(1)</script>'}]),'');
const steps={...base,kind:'step_reveal',steps:[{title:'<img src=x onerror=alert(1)>',body:'<script>alert(1)</script>',source_indices:[1,0,-1,'2']},{title:'测量',body:'观察反应',source_indices:[]}]};
let html=render([steps]);
assert.ok(!html.includes('<script>')&&!html.includes('<img'));
assert.ok(html.includes('&lt;script&gt;')&&html.includes('data-tutor-citation="1"'));
assert.ok(!html.includes('data-tutor-citation="0"')&&!html.includes('data-tutor-citation="2"'));
assert.ok(html.includes('第 1 步')&&html.includes('第 2 步'));
globalThis.sessionStorage={getItem:()=>JSON.stringify([true,true,false])};
html=render([steps]);assert.equal((html.match(/ open>/g)||[]).length,2);
const comparison=render([{...base,kind:'concept_comparison',labels:['自变量','因变量'],rows:[{aspect:'判断',left:'操纵',right:'测量',source_indices:[]}]}]);
assert.ok(comparison.includes('<table>')&&comparison.includes('scope="col"')&&comparison.includes('scope="row"'));
const progress=render([{...base,kind:'learning_progress',explained:true,pending:true,formative_attempts:2,mastered:true}]);
assert.ok(progress.includes('待独立验证')&&!progress.includes('已掌握')&&!progress.includes('%'));
assert.equal(render([{...base,kind:'learning_progress',explained:true,pending:false,formative_attempts:-1}]),'');
console.log('学习卡片：类型白名单、转义、来源、展开恢复、对比及证据语义通过');
