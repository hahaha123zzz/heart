const PW=process.env.PLAYWRIGHT_PACKAGE || "playwright";
const {chromium}=require(PW);
const {expect}=require(PW+"/test");
const assert=require('node:assert/strict');
const TARGET_URL=process.env.MEMORY_ACCEPTANCE_URL || 'http://127.0.0.1:8011';
const OUTPUT_DIR=process.env.MEMORY_ACCEPTANCE_OUTPUT || __dirname;
require('node:fs').mkdirSync(OUTPUT_DIR,{recursive:true});
module.exports=(async () => {
const browser=await chromium.launch({headless:false});
const page=await browser.newPage({viewport:{width:1440,height:1000}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
const checks=[];const mark=name=>{checks.push(name);console.log('PASS '+name)};
const base='/api/students/demo-memory-acceptance/memory';
const overview=async point=>{const r=await page.request.get(TARGET_URL+base+(point?'?point='+encodeURIComponent(point):''));assert.equal(r.status(),200);return r.json()};
try {
await page.addInitScript(()=>localStorage.setItem('discrete-math-demo-student','demo-memory-acceptance'));
await page.goto(TARGET_URL);
await page.locator('.nav-item[data-view="settings"]').click();
await page.locator('#memory-management summary').click();
await expect(page.locator('#memory-point option')).toHaveCount(2);
await page.locator('#memory-point').selectOption('集合');
await expect(page.locator('#memory-detail')).toContainText('混淆元素与集合');
await expect(page.locator('#memory-detail')).toContainText('有效后台摘要：1 条');
await page.locator('#memory-detail summary').filter({hasText:'查看摘要正文'}).click();
await expect(page.locator('#memory-detail')).toContainText('我正在学习集合');
mark('记忆详情、后台摘要正文与来源可查看');
await page.screenshot({path:require("node:path").join(OUTPUT_DIR,"01-overview.png"),fullPage:true});
const before=await overview('集合');
const form=page.locator('[data-memory-correction="1"]');
await form.locator('textarea').fill('我能区分元素和集合，这个判断不符合我的情况');
await form.getByRole('button',{name:'提交更正'}).click();
await expect(page.locator('[data-memory-correction="1"]')).toHaveCount(0);
const corrected=await overview('集合');
assert.equal(corrected.detail.misconceptions[0].status,'dismissed');
assert.equal(corrected.detail.misconceptions[1].status,'supported');
assert.equal(corrected.detail.state.mastery,before.detail.state.mastery);
mark('更正只修改目标误区，其他误区及掌握估计不变');
await page.locator('[data-forget-pref="answer_length"]').click();
await expect(page.locator('[data-forget-pref="answer_length"]')).toHaveCount(0);
assert.equal((await overview()).preferences.some(x=>x.key==='answer_length'),false);
mark('清除指定偏好并同步页面');
await page.locator('#settings-form select[name="answer_length"]').selectOption('0');
await page.locator('#settings-form').getByRole('button',{name:'保存设置'}).click();
await expect(page.locator('[data-forget-pref="answer_length"]')).toHaveCount(1);
assert.equal((await overview()).preferences.find(x=>x.key==='answer_length').source,'explicit_user');
mark('重新保存偏好及来源展示');
await page.screenshot({path:require("node:path").join(OUTPUT_DIR,"02-correction.png"),fullPage:true});
page.once('dialog',d=>d.accept());
await page.locator('#memory-forget-point').click();
await expect(page.locator('#memory-point option')).toHaveCount(1);
assert.deepEqual((await overview()).points,['关系']);
await expect(page.locator('#chat-page-messages')).toContainText('我正在学习关系');
mark('删除集合记忆，关系知识点及其对话保留');
await page.reload();
await page.locator('.nav-item[data-view="settings"]').click();
await page.locator('#memory-management summary').click();
await expect(page.locator('#memory-point option')).toHaveCount(1);
await page.screenshot({path:require("node:path").join(OUTPUT_DIR,"03-after-delete.png"),fullPage:true});
mark('刷新后被删记忆未复活');
// 使用真实 SSE 路由和模拟模型，验证删后新回合。
await page.locator('.nav-item[data-view="chat"]').click();
await page.locator('#chat-page-input').fill('我想学集合，什么是集合的交集？');
const chatResponse=page.waitForResponse(r=>r.url().endsWith('/api/chat/stream'));
await page.locator('#chat-page-form button').click();
const response=await chatResponse;const stream=await response.text();
assert.ok(stream.includes('event: done'),stream.slice(-600));
assert.ok(!stream.includes('event: error'),stream.slice(-600));
mark('删除后新提问经 SSE 返回完成事件');
await expect(page.locator('#chat-page-form button')).toBeEnabled({timeout:30000});
await page.locator('.nav-item[data-view="settings"]').click();
await page.locator('#memory-refresh').click();
await expect.poll(async()=> (await overview()).points.includes('集合'),{timeout:10000}).toBe(true);
await expect.poll(async()=> (await overview('集合')).detail.background_memory.length,{timeout:10000}).toBeGreaterThan(0);
mark('新学习重新建记忆且后台 worker 自动生成摘要');
assert.deepEqual(errors,[]);mark('页面无未捕获 JavaScript 异常');
require('node:fs').writeFileSync(require("node:path").join(OUTPUT_DIR,"browser-results.json"),JSON.stringify({checks,errors,mock:true,realApi:false},null,2));
} finally {await browser.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});
